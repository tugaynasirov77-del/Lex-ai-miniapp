export function pluralDay(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "день";
  if ([2, 3, 4].includes(m10) && ![12, 13, 14].includes(m100)) return "дня";
  return "дней";
}

export function pluralMaterials(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "материал";
  if ([2, 3, 4].includes(m10) && ![12, 13, 14].includes(m100)) return "материала";
  return "материалов";
}

export function renderReminder(
  trigger: ReminderTrigger,
  vars: { N?: number },
  dayOfYear: number,
): string {
  const list = REMINDER_TEXTS[trigger];
  const tpl = list[dayOfYear % list.length];
  let s = tpl.text;
  if (vars.N !== undefined) {
    s = s.replace(/\{N\}/g, String(vars.N))
      .replace(/\{DAYS\}/g, pluralDay(vars.N))
      .replace(/\{MATERIALS\}/g, pluralMaterials(vars.N));
  }
  return s;
}
